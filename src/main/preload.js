  onSelectionDraft: (cb) => ipcRenderer.on('selection-draft', (_, text) => cb(text)),
  onBilibiliAuthChanged: (cb) => { ipcRenderer.removeAllListeners('bilibili-auth-changed'); ipcRenderer.on('bilibili-auth-changed', (_, state) => cb(state)); },
