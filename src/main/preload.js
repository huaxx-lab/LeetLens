  onLearningConversationsUpdated: (cb) => { ipcRenderer.removeAllListeners('learning-conversations-updated'); ipcRenderer.on('learning-conversations-updated', (_, updates) => cb(updates)); },
  onLeetCodeUpdated: (cb) => { ipcRenderer.removeAllListeners('leetcode-updated'); ipcRenderer.on('leetcode-updated', (_, dashboard) => cb(dashboard)); },
  onLeetCodeJudgeProgress: (cb) => { ipcRenderer.removeAllListeners('leetcode-judge-progress'); ipcRenderer.on('leetcode-judge-progress', (_, requestId, progress) => cb(requestId, progress)); },

  getDisplayProfile: () => ipcRenderer.invoke('get-display-profile'),
  getClipboard: () => ipcRenderer.invoke('get-clipboard'),
  setClipboard: (text) => ipcRenderer.invoke('set-clipboard', text),
  loadConversations: () => ipcRenderer.invoke('load-conversations'),
  saveConversation: (id, data) => ipcRenderer.invoke('save-conversation', id, data),
  deleteConversation: (id) => ipcRenderer.invoke('delete-conversation', id),
  getSettings: () => ipcRenderer.invoke('get-settings'),
