  deleteLearningTemplate: (topicPath) => ipcRenderer.invoke('delete-learning-template', topicPath),
  prepareLearningPackage: (itemId, requestedType, force = false) => ipcRenderer.invoke('prepare-learning-package', itemId, requestedType, force),
  judgeLearningAttempt: (itemId, answer) => ipcRenderer.invoke('judge-learning-attempt', itemId, answer),
  validateLearningCode: (language, code) => ipcRenderer.invoke('validate-learning-code', language, code),
  formatLearningCode: (language, code, cursorOffset) => ipcRenderer.invoke('format-learning-code', language, code, cursorOffset),
  patchLearningItem: (itemId, patch, options) => ipcRenderer.invoke('patch-learning-item', itemId, patch, options),
  deleteLearningItem: (itemId, options) => ipcRenderer.invoke('delete-learning-item', itemId, options),
  restoreLearningItem: (itemId) => ipcRenderer.invoke('restore-learning-item', itemId),
  purgeLearningItem: (itemId) => ipcRenderer.invoke('purge-learning-item', itemId),
  purgeAllLearningItems: () => ipcRenderer.invoke('purge-all-learning-items'),
